const assert=require('node:assert/strict');
const fs=require('node:fs'),path=require('node:path'),vm=require('node:vm');
const ctx={window:{}};vm.createContext(ctx);
for(const file of ['post-class-lesson-alignment-data.js','post-class-lesson-alignment.js'])vm.runInContext(fs.readFileSync(path.join(__dirname,'..',file),'utf8'),ctx);
const data=ctx.window.DINO_POST_CLASS_LESSON_ALIGNMENT;
const summary=ctx.window.DinoPostClassLessonAlignment.summarize(data);
assert.equal(data.meta.populationSessions,1856);
assert.equal(data.meta.withSelectedContent+data.meta.withoutSelectedContent,data.meta.populationSessions);
assert.equal(Object.values(data.summary).reduce((sum,value)=>sum+value,0),data.meta.sampleSize);
assert.equal(data.byLevel.reduce((sum,row)=>sum+row.sample,0),data.meta.sampleSize);
for(const row of data.byLevel)assert.equal(row.aligned+row.related+row.drifted+row.insufficient,row.sample);
assert.equal(summary.centered,51);
assert.equal(summary.assessable,55);
assert.equal(Number((summary.centeredRate*100).toFixed(1)),92.7);
assert.equal(Number((summary.coverageRate*100).toFixed(1)),83.2);
assert.ok(data.evidence.some(item=>item.verdict==='aligned'));
assert.ok(data.evidence.some(item=>item.verdict==='drifted'));
assert.ok(data.evidence.every(item=>item.selected&&item.observed&&item.excerpt));
assert.deepEqual([...new Set(data.evidence.map(item=>item.level))].sort(),['L1','L2','L3','L4']);
assert.ok(data.evidence.every(item=>item.id&&Array.isArray(item.conversation)&&item.conversation.length>=2));
assert.ok(data.evidence.every(item=>item.conversation.every(message=>['child','dino'].includes(message[0])&&message[1])));
assert.ok(data.evidence.every(item=>item.conversation.every(message=>/^\d{4}-\d{2}-\d{2} \d{2}:\d{2}:\d{2}$/.test(message[3]))));
const localized=data.evidence.flatMap(item=>item.conversation.filter(message=>message[2]));
assert.ok(localized.some(message=>message[1]==='我准备好了.'&&message[2]==="I'm ready."));
assert.ok(localized.every(message=>message[2]!=='Translated from Chinese'));
console.log(JSON.stringify({status:'PASS',sample:data.meta.sampleSize,assessable:summary.assessable,centered:summary.centered,centeredRate:summary.centeredRate,coverageRate:summary.coverageRate}));
